# Далее идут функции главного меню и меню выбора
def main_menu():
    menu = types.ReplyKeyboardMarkup(resize_keyboard=True)
    menu.row("Подобрать маршрут", "Достопримечательности")
    menu.row("Рассчитать стоимость", "О боте")
    menu.row("Помощь")
    return menu


def places_menu():
    menu = types.ReplyKeyboardMarkup(resize_keyboard=True, row_width=1)
    for name in places:
        menu.add(types.KeyboardButton(name))
    menu.add(types.KeyboardButton("Главное меню"))
    return menu

